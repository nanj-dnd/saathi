"""Builds every per-language file from shared/languages.json and shared/i18n/*.json.

    python3 shared/i18n/build.py

Each language's translation lives in a batch file shared/i18n/_batch*.json, keyed by tag, holding its app strings ("strings", the same names as
android/app/src/main/res/values/strings.xml) and the fixed spoken lines ("lines"). The six recipe
languages keep their hand-written values-xx/strings.xml; their fixed lines live in base-lines.json.
Writes:
  android/app/src/main/res/values-<q>/strings.xml   one per i18n language
  android/app/src/main/java/app/saathi/LanguageList.kt
  shared/fixed-lines.json                            read by the Worker
"""
import json, os, re, sys, xml.etree.ElementTree as ET
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
RES = os.path.join(ROOT, 'android/app/src/main/res')
LINES = ['app_choice', 'unreadable', 'sorry', 'not_installed', 'already', 'opening']
RECIPE = ['hi-IN', 'en-IN', 'ta-IN', 'te-IN', 'kn-IN', 'ml-IN']

registry = json.load(open(os.path.join(ROOT, 'shared/languages.json')))['languages']
base_names = [e.get('name') for e in ET.parse(os.path.join(RES, 'values/strings.xml')).getroot()
              if e.get('translatable') != 'false']

def qualifier(tag):
    lang = tag.split('-')[0]
    lang = {'he': 'iw', 'id': 'in'}.get(lang, lang)
    return f'b+{lang}' if len(lang) == 3 else lang

def esc(s):
    s = s.replace('\\', '\\\\').replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    s = s.replace("'", "\\'").replace('"', '\\"')
    if s[:1] in '@?': s = '\\' + s
    return s

fixed = json.load(open(os.path.join(HERE, 'base-lines.json')))
import glob
translations = {}
for path in sorted(glob.glob(os.path.join(HERE, '_batch*.json'))):
    for tag, data in json.load(open(path)).items():
        if tag in translations: print(f'{tag} appears twice; using {os.path.basename(path)}')
        translations[tag] = data
problems = []
untranslated = []
for entry in registry:
    tag = entry['tag']
    if tag in RECIPE or tag == 'en-US':
        continue
    data = translations.get(tag)
    if data is None:
        # Untranslated: the app's English strings and English fixed lines stand in; guidance is still spoken in the language.
        untranslated.append(tag); continue
    strings, lines = data.get('strings', {}), data.get('lines', {})
    lines.setdefault('unreadable', strings.get('say_unreadable'))  # the same sentence; later batches give it once
    missing = [n for n in base_names if not strings.get(n)]
    if missing: problems.append(f'{tag}: missing strings {missing}')
    for k in LINES:
        if not lines.get(k): problems.append(f'{tag}: missing line {k}')
        elif k in ('not_installed', 'already', 'opening') and '{app}' not in lines[k]: problems.append(f'{tag}: {k} lacks {{app}}')
        else: fixed[k][tag] = lines[k]
    if strings.get('step_count') and ('%1$d' not in strings['step_count'] or '%2$d' not in strings['step_count']):
        problems.append(f'{tag}: step_count placeholders')
    out = os.path.join(RES, f'values-{qualifier(tag)}')
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, 'strings.xml'), 'w') as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by shared/i18n/build.py from %s in shared/i18n/_batch*.json. Edit that. -->\n<resources>\n' % tag)
        for n in base_names:
            if strings.get(n): f.write(f'    <string name="{n}">{esc(strings[n])}</string>\n')
        f.write('</resources>\n')

json.dump(fixed, open(os.path.join(ROOT, 'shared/fixed-lines.json'), 'w'), ensure_ascii=False, indent=1)

def kt(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'
with open(os.path.join(ROOT, 'android/app/src/main/java/app/saathi/LanguageList.kt'), 'w') as f:
    f.write('// Generated by shared/i18n/build.py from shared/languages.json and shared/i18n. Do not edit.\npackage app.saathi\n\n')
    f.write('/** One language Bob offers: its tag, its own name, its English name, and where the picker lists it. */\n')
    f.write('data class Language(val tag: String, val native: String, val english: String, val india: Boolean, val rtl: Boolean)\n\n')
    f.write('object LanguageList {\n    val ALL = listOf(\n')
    for e in registry:
        f.write(f'        Language({kt(e["tag"])}, {kt(e["native"])}, {kt(e["english"])}, {str(e["region"]=="india").lower()}, {str(e["rtl"]).lower()}),\n')
    f.write('    )\n\n')
    for k, name in (('not_installed', 'NOT_INSTALLED'), ('already', 'ALREADY'), ('opening', 'OPENING')):
        f.write(f'    /** The fixed "{k}" line for every language; {{app}} is the app\'s name. */\n    val {name}: Map<String, String> = mapOf(\n')
        for tag, text in fixed[k].items():
            f.write(f'        {kt(tag)} to {kt(text)},\n')
        f.write('    )\n\n')
    f.write('}\n')

n = sum(1 for e in registry if e['tag'] not in RECIPE and e['tag'] != 'en-US')
print(f'{len(registry)} languages; {n - len(untranslated)} translated here, {len(untranslated)} on English fallback; {len(problems)} problems')
if untranslated: print('   English fallback:', ' '.join(untranslated))
for p in problems: print('  ', p)
sys.exit(1 if problems else 0)
